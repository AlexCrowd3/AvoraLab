// Единый источник данных по услугам.
//
// Отсюда берут контент:
//   • карточки на /services (ServiceCards),
//   • карточки на главной (WhatWeBuild),
//   • отдельные страницы услуг (/services/:slug),
//   • генератор sitemap.xml и статических HTML-страниц (scripts/prerender.mjs).
//
// slug — ЧПУ-адрес страницы услуги, участвует в URL и в sitemap, поэтому
// должен быть уникальным и состоять только из латиницы и дефисов.
//
// ВАЖНО: цены и сроки здесь — те же, что были на сайте до появления
// отдельных страниц услуг. Новые цифры не выдумывались: если по услуге
// нет фиксированной стоимости, в priceNote честно написано, что расчёт
// индивидуальный.


export interface ServiceStage {
  title: string
  text: string
}

export interface ServiceFaq {
  q: string
  a: string
}

export interface Service {
  /** ЧПУ-адрес: /services/<slug> */
  slug: string
  /** Короткое имя услуги — для меню, хлебных крошек и подстановки в форму заявки. */
  shortTitle: string
  /** Заголовок карточки на /services и на главной (оставлен прежним). */
  cardTitle: string
  /** Единственный H1 страницы услуги. */
  h1: string
  /** <title> страницы — уникальный, до ~60 символов + бренд. */
  seoTitle: string
  /** <meta name="description"> — уникальный, 140–165 символов. */
  seoDescription: string
  /** Ключевые запросы: используются в тексте естественно, не для спама в meta keywords. */
  keywords: string[]
  /** Подзаголовок под H1. */
  lead: string
  /** «Что это такое» — 1–2 абзаца человеческим языком. */
  about: string[]
  /** «Кому подходит». */
  forWhom: string[]
  /** «Что входит в разработку» — тот же список, что на карточке. */
  includes: string[]
  /** «Что вы получите на выходе». */
  results: string[]
  /** Этапы работы по услуге. */
  stages: ServiceStage[]
  /** Ориентировочный срок — формулировка с карточки. */
  duration: string
  /** Стоимость: строка с карточки либо null, если цена только индивидуальная. */
  price: string | null
  /** Пояснение к цене — что входит в минимальную стоимость и от чего она растёт. */
  priceNote: string
  /** Что влияет на итоговую стоимость. */
  priceFactors: string[]
  /** Текст кнопки заказа. */
  ctaLabel: string
  /** Slug'и кейсов из data/cases.ts, которые показываем как портфолио. */
  caseSlugs: string[]
  /** Вопросы и ответы. Используются и в разметке FAQPage. */
  faq: ServiceFaq[]
  /** Перелинковка: slug'и смежных услуг. */
  related: string[]
  /** Оформление карточки — существующие классы, менять не нужно. */
  cardClass: string
  /** Ширина текстовой колонки в карточке на /services. */
  textWidth: number
  /** Бейдж на карточке. */
  badge?: string
  /** Краткое описание на карточке. */
  cardDesc: string
  /** Строка стоимости на карточке — сохранена в точности как на текущем сайте. */
  cardPrice: string
  /** Подпись на кнопке карточки — сохранена в точности как на текущем сайте. */
  cardDuration: string
  /** Картинка-превью услуги (используется в шапке страницы услуги). */
  image: string
  /** alt для картинки — осмысленный, а не «картинка». */
  imageAlt: string
}

